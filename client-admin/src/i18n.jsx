const LangContext = createContext(null);

export function LangProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem('sv_admin_lang') || 'en');

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    localStorage.setItem('sv_admin_lang', lang);
  }, [lang]);

  const value = useMemo(
    () => ({
      lang,
      dir: lang === 'ar' ? 'rtl' : 'ltr',
      setLang,
      t: (k) => dict[lang][k] ?? dict.en[k] ?? k,
      // Arabic is optional in the data: a row imported from a sheet with no
      // Arabic stores NULL. Fall back to English, and treat blank as missing.
      pick: (obj, base) => {
        const wanted = obj?.[`${base}${lang === 'ar' ? 'Ar' : 'En'}`];
        if (wanted != null && String(wanted).trim() !== '') return wanted;
        return obj?.[`${base}En`] ?? '';
      },
    }),
    [lang]
  );

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export const useLang = () => useContext(LangContext);
